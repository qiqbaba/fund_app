import re

def extract_fund_sector(name, code=None):
    """
    从基金名称或代码中智能提取板块名称。
    支持：1. 特定代码映射 2. 优先级关键词匹配 3. 冗余清理
    """
    if not name and not code:
        return "未知"
        
    # --- 0. 特定基金代码硬编码映射 (高优先级) ---
    code_mapping = {
        "001592": "创业板", "001593": "创业板", "161725": "白酒",
        "001611": "计算机", "001612": "计算机", "512480": "半导体",
        "013445": "芯片", "512760": "芯片",
        "001631": "电子", "001632": "电子",
        "004243": "军工", "160643": "军工", "512660": "军工",
        "000216": "黄金", "000373": "生物医药", "512010": "医药",
        "161028": "新能源车", "001156": "新能源车",
        "005939": "新能源", "512170": "医疗",
        "000051": "沪深300", "510300": "沪深300", "110020": "沪深300",
        "510500": "中证500", "000478": "中证500",
        "512100": "中证1000", "011860": "中证1000",
        "159915": "创业板", "588000": "科创50", "019305": "A500",
        "003003": "纳斯达克100", "513100": "纳斯达克100", "048003": "标普500",
        "004752": "家电", "160632": "资源", "161715": "大消费",
        "160626": "农业", "001610": "中药",
        "017513": "北证50", "021232": "中证A50", "022460": "A500",
    }
    if code and code in code_mapping:
        return code_mapping[code]

    # --- 1. 优先级关键词 (按细分程度排序) ---
    # 细分板块优先于宽基/大类，且按“最具体->最广泛”排序
    priority_keywords = [
        # --- 科技细分 ---
        ('半导体设备',), ('芯片',), ('半导体',), 
        ('人工智能', 'AI'), ('算力', '大模型', '服务器'),
        ('数据要素', '数据'), ('软件', '信创'), ('计算机', 'IT'), 
        ('低空经济', '飞行汽车'), ('机器人', '自动化'),
        ('游戏', '动漫'), ('传媒', '数字媒体'), ('互联网',), ('移动互联',),
        # --- 通信/电子 ---
        ('5G', '6G'), ('通信',), ('电子',),
        # --- 医疗细分 ---
        ('创新药',), ('中药',), ('医疗器械',), ('医疗服务',), ('医药',), ('生物医药', '生物'),
        # --- 消费细分 ---
        ('白酒', '酒'), ('食品', '饮料'), ('乳业',), ('畜牧', '养殖', '猪肉'), 
        ('旅游', '免税', '休闲'), ('家电',), ('农业',), ('大消费', '消费'),
        # --- 资源/金属 (细化调整) ---
        ('稀有金属', '稀金'), ('稀土',), ('黄金', '贵金属'), 
        ('工业金属', '有色', '金属'), # “有色”作为兜底放在后面
        ('煤炭',), ('原油', '石油'), ('天然气',), ('能源',),
        ('钢铁',), ('化工',), ('建材',), 
        # --- 制造/基建 ---
        ('高端装备', '高端制造', '先进制造'), ('机械',), ('建筑', '基建'), ('地产', '房地产'),
        ('电力', '绿电', '电网'), ('环保',),
        # --- 新能源 ---
        ('光伏', '硅片'), ('锂电池', '电池'), ('储能',), ('新能源', '碳中和'), ('汽车', '新能源车'),
        # --- 金融 (细化调整) ---
        ('证券', '券商'), ('银行',), ('保险',), ('金融',),
        # --- 军工/航天 ---
        ('卫星', '航天', '航空'), ('商业航天',), ('军工', '国防'),
        # --- 宽基指数/大类 ---
        ('纳斯达克100', '纳斯达克', '纳指'), ('标普500', '标普'), ('恒生科技', '恒生'), 
        ('科创200', '科创板200'), ('科创100', '科创板100'), ('科创50', '科创板50'),
        ('双创50', '科创创业50', '科创创业'), ('A500',), ('中证A50',), ('沪深300',), ('中证500',), ('中证1000',), 
        ('中证2000',), ('上证50',), ('北证50',), ('创业板',), ('红利', '高股息'),
        # --- 其他/海外 ---
        ('全球',), ('欧洲',), ('港股',), ('美股',), ('日本', '日经'), ('德国',), ('越南',), ('印度',), ('亚太',)
    ]

    # 清理后的匹配逻辑
    def match_keywords(target_text):
        for group in priority_keywords:
            for kw in group:
                if kw in target_text:
                    return group[0] # 返回组内第一个作为标准名称
        return None

    # 第一轮：直接匹配完整名称
    matched = match_keywords(name)
    if matched: return matched

    # 第二轮：清理冗余信息后匹配
    company_prefixes = (
        '华夏|易方达|广发|富国|招商|嘉实|南方|博时|鹏华|汇添富|天弘|华安|国泰|银华|'
        '工银|建信|交银|景顺长城|景顺|中欧|华宝|大成|前海开源|国联安|国联|兴银|永赢|中银|'
        '万家|中融|国金|平安|浦银安盛|长城|长信|长盛|东方|方正富邦|海富通|华泰柏瑞|'
        '华泰|华富|汇安|金鹰|民生加银|民生|农银汇理|农银|诺安|诺德|融通|上投摩根|上投|'
        '泰达宏利|泰达|泰康|西部利得|西部|信达澳亚|信达澳银|信达|兴全|兴业|'
        '鑫元|银河|英大|圆信永丰|招商|中海|中加|中金|中信保诚|中信建投|中信|中邮|'
        '景顺长城|景顺|东财'
    )
    
    # 移除后缀和中性词
    clean_name = re.sub(r'(ETF|LOF|联接|发起式|指数|增强|型|证券投资基金|[A-E]\b).*$', '', name)
    # 移除公司前缀
    clean_name = re.sub(r'^(' + company_prefixes + ')', '', clean_name)
    clean_name = clean_name.strip()
    
    matched = match_keywords(clean_name)
    if matched: return matched
    
    # 特殊补丁：处理一些常见的被截断的关键词
    if '成份' in clean_name: clean_name = clean_name.replace('成份', '')
    if '混合' in clean_name: clean_name = clean_name.replace('混合', '')

    # 第三轮：回退逻辑
    if clean_name:
        # 如果长度小于等于8，直接返回全文，避免截断数字
        return clean_name if len(clean_name) <= 8 else clean_name[:6]
    
    return name[:6] if len(name) >= 2 else "未知"

